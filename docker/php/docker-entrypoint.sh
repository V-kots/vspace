#!/bin/sh
set -e

# Bind-mount ./src приходит с хоста под uid пользователя, а php-fpm-воркеры
# работают под www-data. Гарантируем запись в storage и bootstrap/cache, чтобы
# свежая копия проекта работала без ручного chown.
mkdir -p /var/www/html/storage/framework/views \
    /var/www/html/storage/framework/cache/data \
    /var/www/html/storage/framework/sessions \
    /var/www/html/storage/logs
for dir in /var/www/html/storage /var/www/html/bootstrap/cache; do
    [ -e "$dir" ] || continue
    owner="$(stat -c '%U' "$dir" 2>/dev/null || echo '')"
    if [ "$owner" != "www-data" ]; then
        chown -R www-data:www-data "$dir" || true
    fi
done

validate="${PHP_OPCACHE_VALIDATE_TIMESTAMPS:-0}"
jit="${PHP_OPCACHE_JIT:-1255}"
preload="${PHP_OPCACHE_PRELOAD:-1}"

{
  echo "; generated by docker-entrypoint.sh — do not edit"
  echo "opcache.validate_timestamps=${validate}"
  echo "opcache.jit=${jit}"
  if [ "${preload}" = "1" ] \
    && [ -f /var/www/html/bootstrap/preload.php ] \
    && [ -f /var/www/html/vendor/autoload.php ]; then
    echo "opcache.preload=/var/www/html/bootstrap/preload.php"
    echo "opcache.preload_user=www-data"
  fi
} > /usr/local/etc/php/conf.d/98-opcache-runtime.ini

xdebug_ini="/usr/local/etc/php/conf.d/docker-php-ext-xdebug.ini"
xdebug_ini_off="/usr/local/etc/php/conf.d/docker-php-ext-xdebug.ini.disabled"

xdebug_mode="${XDEBUG_MODE:-off}"
if [ "${xdebug_mode}" = "off" ] || [ -z "${xdebug_mode}" ]; then
  # Xdebug перехватывает zend_execute_ex → JIT не работает; для load полностью выгружаем ext.
  if [ -f "${xdebug_ini}" ]; then
    mv "${xdebug_ini}" "${xdebug_ini_off}"
  fi
  rm -f /usr/local/etc/php/conf.d/97-xdebug-fpm.ini
else
  if [ -f "${xdebug_ini_off}" ]; then
    mv "${xdebug_ini_off}" "${xdebug_ini}"
  fi
  cat > /usr/local/etc/php/conf.d/97-xdebug-fpm.ini <<'EOF'
; XDEBUG_MODE!=off — step debug на запрос (короткий connect timeout)
[xdebug]
xdebug.start_with_request=yes
xdebug.connect_timeout_ms=150
EOF
fi

exec docker-php-entrypoint "$@"
